"""
translate_predictions.py
Utility script to display raw model outputs (35x35 prediction matrices) for 2D CNN and GNN models,
and translate matrix entries into human-readable PowerWorld AUX power system devices
(Buses, Transmission Lines, Transformers, Generators, Loads) that require N-1 contingency stress-testing.

Also exports a PowerWorld-compliant Auxiliary Contingency Study file (data/n1_study_recommendations.aux).
"""

import os
import json
import numpy as np
import tensorflow as tf
from tensorflow import keras

from grid_generator import load_powerworld_aux, generate_35bus_grid
from gnn_model import extract_graph_features, GraphConvLayer, PairPredictionHead
from model import load_dataset
from train import weighted_bce_loss, F1ScoreMetric


def translate_matrix_to_devices(binary_matrix, prob_matrix, grid_data, threshold=0.5):
    """
    Translates a 35x35 binary recommendation matrix and probability matrix
    into explicit PowerWorld AUX power system devices (Branches and Buses).

    Returns:
        study_list (list of dict): Detailed list of recommended devices to stress-test.
    """
    num_buses = 35
    buses_dict = {b['bus_num']: b for b in grid_data['buses']}
    branches_dict = {}
    for br in grid_data['branches']:
        key = (min(br['from_bus'], br['to_bus']), max(br['from_bus'], br['to_bus']))
        branches_dict[key] = br

    study_list = []
    processed_pairs = set()

    for i in range(num_buses):
        for j in range(num_buses):
            if binary_matrix[i, j] >= 0.5:
                bus_i = i + 1
                bus_j = j + 1
                prob_val = float(prob_matrix[i, j])

                if i == j:
                    # Diagonal entry: Bus & Connected Generators/Loads
                    b_info = buses_dict.get(bus_i, {})
                    b_name = b_info.get('bus_name', f'Bus_{bus_i}')
                    b_kv = b_info.get('base_kv', 230.0)

                    study_list.append({
                        'category': 'BUS_DEVICE',
                        'device_type': 'BUS / GENERATOR / LOAD',
                        'from_bus': bus_i,
                        'to_bus': bus_i,
                        'from_name': b_name,
                        'to_name': b_name,
                        'description': f"BUS {bus_i} ({b_name}, {b_kv} kV) - Stress-test connected Generators & Loads",
                        'probability': round(prob_val, 4)
                    })
                else:
                    # Off-diagonal entry: Transmission Line / Transformer Branch
                    pair_key = (min(bus_i, bus_j), max(bus_i, bus_j))
                    if pair_key in processed_pairs:
                        continue
                    processed_pairs.add(pair_key)

                    br_info = branches_dict.get(pair_key, {})
                    b_name_i = buses_dict.get(bus_i, {}).get('bus_name', f'Bus_{bus_i}')
                    b_name_j = buses_dict.get(bus_j, {}).get('bus_name', f'Bus_{bus_j}')
                    rate_a = br_info.get('rate_a', 250.0)

                    study_list.append({
                        'category': 'BRANCH',
                        'device_type': 'TRANSMISSION LINE / TRANSFORMER',
                        'from_bus': bus_i,
                        'to_bus': bus_j,
                        'from_name': b_name_i,
                        'to_name': b_name_j,
                        'description': f"BRANCH {bus_i} ({b_name_i}) <-> {bus_j} ({b_name_j}), Circuit '1' (Rating: {rate_a} MVA)",
                        'probability': round(prob_val, 4)
                    })

    return study_list


def export_powerworld_contingency_aux(study_list, output_path='data/n1_study_recommendations.aux'):
    """
    Exports recommended devices into a PowerWorld Auxiliary (.aux) Contingency block format.
    Power engineers can load this .aux file directly into PowerWorld Simulator.
    """
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    with open(output_path, 'w') as f:
        f.write("// PowerWorld Auxiliary File - Recommended N-1 Contingency Study List\n")
        f.write("// Automatically generated by N-1 Contingency Recommendation System\n\n")

        f.write("DATA (CONTINGENCY, [ContingencyName, ContingencyElement, ElementType, Action, BusNum, BusNum:1, Circuit])\n{\n")
        
        cont_idx = 1
        for item in study_list:
            c_name = f'"N1_STRESS_TEST_{cont_idx:03d}"'
            if item['category'] == 'BRANCH':
                f.write(f'  {c_name} "OPEN BRANCH {item["from_bus"]} {item["to_bus"]}" "BRANCH" "OPEN" {item["from_bus"]} {item["to_bus"]} "1"\n')
            else:
                f.write(f'  {c_name} "OPEN BUS {item["from_bus"]}" "BUS" "OPEN" {item["from_bus"]} 0 "1"\n')
            cont_idx += 1

        f.write("}\n")

    print(f"Successfully exported PowerWorld Contingency AUX file to: {output_path}")


def inspect_sample_predictions(sample_idx=0, dataset_path='data/dataset.npz', aux_path='data/grid_35bus.aux'):
    """
    Runs CNN and GNN inference on a specific sample and translates outputs into power devices.
    """
    # 1. Load Data & Grid Model
    _, _, (x_test, y_test) = load_dataset(dataset_path)
    if os.path.exists(aux_path):
        grid_data = load_powerworld_aux(aux_path)
    else:
        grid_data = generate_35bus_grid(seed=42)

    sample_x = x_test[sample_idx:sample_idx+1]  # shape (1, 35, 35, 3)
    sample_y = y_test[sample_idx]              # shape (35, 35)

    # 2. Run CNN Model Inference
    cnn_path = 'checkpoints/best_model.keras'
    loss_fn = weighted_bce_loss(pos_weight=15.0)
    cnn_model = keras.models.load_model(cnn_path, custom_objects={'loss_fn': loss_fn, 'F1ScoreMetric': F1ScoreMetric})
    cnn_logits = cnn_model.predict(sample_x, verbose=0)[0]
    cnn_probs = 1.0 / (1.0 + np.exp(-cnn_logits))
    cnn_binary = (cnn_probs >= 0.5).astype(np.float32)

    # 3. Run GNN Model Inference
    gnn_path = 'checkpoints/best_gnn_model.keras'
    custom_gnn_objects = {
        'loss_fn': loss_fn,
        'extract_graph_features': extract_graph_features,
        'F1ScoreMetric': F1ScoreMetric,
        'GraphConvLayer': GraphConvLayer,
        'PairPredictionHead': PairPredictionHead
    }
    gnn_model = keras.models.load_model(gnn_path, custom_objects=custom_gnn_objects, safe_mode=False)
    gnn_logits = gnn_model.predict(sample_x, verbose=0)[0]
    gnn_probs = 1.0 / (1.0 + np.exp(-gnn_logits))
    gnn_binary = (gnn_probs >= 0.5).astype(np.float32)

    print("\n" + "=" * 80)
    print(f"      MODEL OUTPUT INSPECTION FOR TEST SAMPLE #{sample_idx}")
    print("=" * 80)

    # Print Raw 35x35 Binary Matrix Slice (First 10x10 sub-matrix for preview)
    print("\n--- RAW MATRIX OUTPUT PREVIEW (10x10 Sub-matrix slice) ---")
    print("Ground Truth Y [10x10]:")
    print(sample_y[:10, :10].astype(int))
    
    print("\nCNN Binary Output (p >= 0.5) [10x10]:")
    print(cnn_binary[:10, :10].astype(int))

    print("\nGNN Binary Output (p >= 0.5) [10x10]:")
    print(gnn_binary[:10, :10].astype(int))

    # 4. Translate Matrix Predictions to Power System Devices
    cnn_study_list = translate_matrix_to_devices(cnn_binary, cnn_probs, grid_data)
    gnn_study_list = translate_matrix_to_devices(gnn_binary, gnn_probs, grid_data)

    print("\n" + "=" * 80)
    print("      TRANSLATED POWER SYSTEM DEVICE RECOMMENDATIONS (GNN MODEL)")
    print("=" * 80)
    print(f"{'Category':<15} | {'Device Description':<55} | {'Risk Prob':<10}")
    print("-" * 85)

    for item in gnn_study_list:
        print(f"{item['category']:<15} | {item['description']:<55} | {item['probability']:.4f}")

    print("=" * 80)
    print(f"Total Recommended Devices to Stress-Test: {len(gnn_study_list)}")
    print("=" * 80)

    # Export to PowerWorld AUX format
    export_powerworld_contingency_aux(gnn_study_list)

    return gnn_study_list


if __name__ == '__main__':
    inspect_sample_predictions(sample_idx=0)
